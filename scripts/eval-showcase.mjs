// Builds public/evaluation-lessons.mjs: a curated set of lessons the Muse models drafted during
// a frozen Studio evaluation run, shown in the library unedited with their scores.
//
// Usage: node scripts/eval-showcase.mjs <run directory>
// The run directory is what scripts/eval-studio.mjs --live wrote (one <model>/report.json per
// model). It is never committed; only the selected lessons below are. Each selection names the
// pair, the case (the learner question, in its language) and the model whose reply is shown.
// `compare` marks the cases where both models' replies are kept so the app can show them side
// by side; those cases must have the same question for both models.
import {readFileSync,writeFileSync,readdirSync} from 'node:fs';
import {validateLesson} from '../public/lesson-schema.mjs';
import {loadStudioSuite} from '../src/eval/studio.mjs';

const WONDER='muse-wonder-1.0',SPARK='muse-spark-1.3';
// Primary pick per pair: the higher judge score; ties alternate between the two models so the
// showcase samples both. Where a case was rejected for one model, the other model's reply shows.
export const selection=Object.freeze([
 {pair:'projectile',caseId:'projectile-zh',model:WONDER},
 {pair:'half-life',caseId:'half-life-en',model:SPARK},
 {pair:'logistic-growth',caseId:'logistic-growth-en',model:WONDER,compare:SPARK},
 {pair:'drug-elimination',caseId:'drug-elimination-zh',model:SPARK},
 {pair:'compound-interest',caseId:'compound-interest-en',model:WONDER},
 {pair:'download-time',caseId:'download-time-zh',model:SPARK},
 {pair:'carbon-dating',caseId:'carbon-dating-en',model:WONDER},
 {pair:'braking-distance',caseId:'braking-distance-zh',model:SPARK},
 {pair:'rc-charging',caseId:'rc-charging-zh',model:WONDER,compare:SPARK},
 {pair:'vaccine-immunity',caseId:'vaccine-immunity-en',model:WONDER},
 {pair:'dns-lookup',caseId:'dns-lookup-zh',model:SPARK,compare:WONDER},
]);
const short=model=>model.startsWith('muse-wonder')?'wonder':model.startsWith('muse-spark')?'spark':model.replace(/[^a-z0-9]+/g,'-');

export function buildShowcase(reports,suite){
 const byModel=new Map(reports.map(r=>[r.metadata.model,r]));
 const question=pair=>Object.fromEntries(['en','zh'].map(l=>[l,suite.cases.find(c=>c.pair===pair&&c.language===l)?.topic]));
 const pick=(entry,model)=>{
  const report=byModel.get(model);if(!report)throw new Error(`No report for ${model}.`);
  const row=report.cases.find(c=>c.id===entry.caseId);
  if(!row)throw new Error(`${entry.caseId} is not in the ${model} report.`);
  if(!row.automatedPass||row.response?.status!=='ready'||!row.judge?.total&&row.judge?.total!==0)throw new Error(`${entry.caseId} (${model}) did not pass or was not judged.`);
  const lesson=validateLesson(structuredClone(row.response.lesson));
  const kind=lesson.chapters[0].demo.kind;
  const q=question(entry.pair);if(!q.en||!q.zh)throw new Error(`Missing question for ${entry.pair}.`);
  return {
   id:`eval-${entry.pair}-${short(model)}`,pair:entry.pair,caseId:entry.caseId,language:row.language,kind,
   model,suite:report.suite,suiteSha256:report.metadata.suiteHash,promptVersion:report.metadata.promptVersion,
   runDate:report.startedAt.slice(0,10),question:q,latencyMs:row.latencyMs,
   tokens:{input:row.usage?.input??null,output:row.usage?.output??null},
   checks:Object.entries(row.checks).filter(([,ok])=>ok).map(([k])=>k),
   judge:{model:row.judge.model,total:row.judge.total,max:row.judge.max,scores:row.judge.scores,issues:row.judge.issues,summary:row.judge.summary},
   lesson,
  };
 };
 const lessons=[],comparisons=[];
 for(const entry of selection){
  const primary=pick(entry,entry.model);lessons.push(primary);
  if(entry.compare){
   const other=pick(entry,entry.compare);lessons.push(other);
   comparisons.push({caseId:entry.caseId,pair:entry.pair,ids:[primary.id,other.id].sort((a,b)=>a.endsWith('-wonder')?-1:b.endsWith('-wonder')?1:0)});
  }
 }
 if(new Set(lessons.map(l=>l.id)).size!==lessons.length)throw new Error('Duplicate showcase ids.');
 return {lessons,comparisons};
}

export function showcaseModule({lessons,comparisons}){
 const body=lessons.map(l=>' '+JSON.stringify(l)).join(',\n');
 return `// Generated by scripts/eval-showcase.mjs from a frozen Studio evaluation run; do not edit by hand.
// Each lesson is a Muse model's reply to the learner question shown, unedited, kept because it
// passed the app's automated checks and was scored by the rubric judge. The author has not
// reviewed the science. Method, results and limits: docs/evaluation.md.
export const evaluationLessons=Object.freeze([
${body}
]);
export const evaluationComparisons=Object.freeze(${JSON.stringify(comparisons)});
export const evaluationIds=Object.freeze(evaluationLessons.map(l=>l.id));
export function evaluationLesson(id){return evaluationLessons.find(l=>l.id===id)??null;}
export function evaluationComparison(caseId){return evaluationComparisons.find(c=>c.caseId===caseId)??null;}
// Deep link: /#compare:logistic-growth-en shows both models' replies to one question.
export function comparisonIdFromHash(hash){const m=/^#compare:([a-z-]+)$/.exec(hash??'');return m&&evaluationComparison(m[1])?m[1]:null;}
const modelName=model=>model.startsWith('muse-wonder')?'Muse Wonder':model.startsWith('muse-spark')?'Muse Spark':model;
export function evaluationModelLabel(model){return modelName(model);}
const dateText=(iso,zh)=>{const [y,m,d]=iso.split('-').map(Number);return zh?\`\${y} 年 \${m} 月 \${d} 日\`:new Date(Date.UTC(y,m-1,d)).toLocaleDateString('en-US',{year:'numeric',month:'long',day:'numeric',timeZone:'UTC'});};
export function evaluationNote(item,language='en'){
 const zh=language==='zh',date=dateText(item.runDate,zh);
 return zh
  ?\`由 Meta \${item.model} 于\${date}在冻结的 \${item.suite} 评估中（用例 \${item.caseId}）根据上面的学习者提问起草，未经编辑原样展示。应用的校验器接受了该契约，自动检查全部通过；评分模型 \${item.judge.model} 打分 \${item.judge.total}/\${item.judge.max}。作者未审阅其中的科学内容：请把它当作模型产出的样本，用于教学前先自行核对。方法与全部结果见评估卡。\`
  :\`Drafted by Meta \${item.model} on \${date} in the frozen \${item.suite} evaluation (case \${item.caseId}) from the learner question above, and shown here unedited. The app's validator accepted the contract and every automated check passed; the rubric judge (\${item.judge.model}) scored it \${item.judge.total}/\${item.judge.max}. The author has not reviewed the science: read it as a sample of what the model produced and check it before teaching from it. Method and all results are in the evaluation card.\`;
}
`;
}

if(process.argv[1]&&import.meta.url===new URL(`file://${process.argv[1]}`).href){
 const dir=process.argv[2];if(!dir)throw new Error('Usage: node scripts/eval-showcase.mjs <run directory>');
 const reports=readdirSync(dir,{withFileTypes:true}).filter(d=>d.isDirectory()).map(d=>JSON.parse(readFileSync(`${dir}/${d.name}/report.json`,'utf8')));
 const suiteName=reports[0]?.suite;if(!suiteName)throw new Error('No reports found.');
 const {suite,sha256}=loadStudioSuite(suiteName);
 for(const r of reports)if(r.metadata.suiteHash!==sha256)throw new Error(`${r.metadata.model} ran a different suite checksum.`);
 const showcase=buildShowcase(reports,suite);
 const out=new URL('../public/evaluation-lessons.mjs',import.meta.url);
 writeFileSync(out,showcaseModule(showcase));
 console.log(`${showcase.lessons.length} lessons, ${showcase.comparisons.length} comparisons → ${out.pathname}`);
 for(const l of showcase.lessons)console.log(`  ${l.id.padEnd(34)} ${l.caseId.padEnd(22)} judge ${l.judge.total}/${l.judge.max} issues ${l.judge.issues.length} ${l.lesson.title.en}`);
}
