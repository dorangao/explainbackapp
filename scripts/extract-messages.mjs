// One-off refactor helper: moves literal `say(language, "en", "zh")` pairs out of the
// components into frontend/lib/messages.ts so every EN/ZH pair can be reviewed in one
// file. Calls whose arguments are not plain string literals are left in place.
// Usage: node scripts/extract-messages.mjs [--write]
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, relative, basename } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
const root = fileURLToPath(new URL("../frontend/", import.meta.url));
const write = process.argv.includes("--write");
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path);
    else if (/\.(tsx|ts)$/.test(name) && !/\.test\.|\.d\.ts$|messages\.ts$/.test(name)) files.push(path);
  }
})(root);
const literal = String.raw`"((?:[^"\\]|\\.)*)"`;
const call = new RegExp(String.raw`say\(\s*language\s*,\s*${literal}\s*,\s*${literal}\s*,?\s*\)`, "g");
const messages = new Map(); // key -> {en, zh}
// Keep every entry already in the table: earlier extractions turned their call sites into t() calls.
try {
  const existing = (await import(pathToFileURL(join(root, "lib/messages.ts")).href)).messages;
  for (const [key, value] of Object.entries(existing)) messages.set(key, { en: value.en, zh: value.zh });
} catch {}
const slug = (text) =>
  text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .trim()
    .split(" ")
    .filter(Boolean)
    .slice(0, 5)
    .map((w, i) => (i ? w[0].toUpperCase() + w.slice(1) : w))
    .join("") || "text";
let total = 0;
const edits = [];
for (const file of files) {
  const source = readFileSync(file, "utf8");
  const component = basename(file).replace(/\.(tsx|ts)$/, "");
  let changed = source,
    count = 0;
  changed = changed.replace(call, (match, en, zh) => {
    const enText = JSON.parse(`"${en}"`),
      zhText = JSON.parse(`"${zh}"`);
    let key = `${component}.${slug(enText)}`;
    let n = 2;
    while (messages.has(key) && (messages.get(key).en !== enText || messages.get(key).zh !== zhText)) key = `${component}.${slug(enText)}${n++}`;
    messages.set(key, { en: enText, zh: zhText });
    count++;
    return `t(language, ${JSON.stringify(key)})`;
  });
  if (count) {
    total += count;
    const needsImport = !/from "\.\.\/lib\/messages"|from "\.\/lib\/messages"/.test(changed);
    if (needsImport) {
      const importPath = relative(join(file, ".."), join(root, "lib/messages")).replace(/\\/g, "/");
      changed = `import { t } from "${importPath.startsWith(".") ? importPath : "./" + importPath}";\n` + changed;
    }
    if (!/\bsay\(/.test(changed)) changed = changed.replace(/import \{ say \} from "([^"]+)";\n/, "").replace(/,\s*say\s*\}/, " }").replace(/\{\s*say\s*,\s*/, "{ ");
    edits.push([file, changed, count]);
  }
}
const sorted = [...messages.entries()].sort(([a], [b]) => a.localeCompare(b));
const table = `// Generated by scripts/extract-messages.mjs from the components' literal EN/ZH pairs.
// Review translations here; keys are <Component>.<english slug>. Non-literal strings stay inline.
import type { Language } from "./types";
export const messages = {
${sorted.map(([key, { en, zh }]) => `  ${JSON.stringify(key)}: { en: ${JSON.stringify(en)}, zh: ${JSON.stringify(zh)} },`).join("\n")}
} as const;
export type MessageKey = keyof typeof messages;
export const t = (language: Language, key: MessageKey): string => messages[key][language];
`;
console.log(`${files.length} files scanned, ${total} literal pairs in ${edits.length} files, ${messages.size} unique messages.`);
if (write) {
  writeFileSync(join(root, "lib/messages.ts"), table);
  for (const [file, changed, count] of edits) {
    writeFileSync(file, changed);
    console.log(`${relative(root, file)}: ${count}`);
  }
} else console.log("Dry run. Pass --write to apply.");
