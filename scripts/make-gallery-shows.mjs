import {writeFile} from 'node:fs/promises';
import {createProviderRouter} from '../src/llm/index.mjs';
import {showRequest,readShow,showPromptVersion,illustrationPrompt} from '../src/lesson-show.mjs';
import {generateMetaImage} from '../src/meta.mjs';
import {galleryLessons} from '../public/gallery-lessons.mjs';
// Usage: node --env-file-if-exists=.env.local scripts/make-gallery-shows.mjs --live [--ids=cooling,pendulum] [--model=meta:muse-wonder-1.0]
// Writes public/gallery-shows.mjs, public/gallery/<id>-cover.webp and, for slides the writer
// flagged, public/gallery/<id>-slide-<n>.webp. Without --live nothing is sent.
const args=process.argv.slice(2),option=name=>args.find(a=>a.startsWith(`--${name}=`))?.slice(name.length+3);
const ids=(option('ids')??galleryLessons.map(l=>l.id).join(',')).split(',').map(s=>s.trim()).filter(Boolean);
const modelId=option('model')??'meta:muse-wonder-1.0';
const existing=await import('../public/gallery-shows.mjs').then(m=>({...m.galleryShows})).catch(()=>({}));
console.log(`shows for ${ids.join(', ')} · script model ${modelId} · cover muse-image-1.0 · ${showPromptVersion}`);
if(!args.includes('--live')){console.log('Dry run; add --live to send requests.');process.exit(0);}
const router=createProviderRouter({env:{...process.env,EXPLAINBACK_PROVIDERS:'meta',EXPLAINBACK_DEFAULT_MODEL:modelId,EXPLAINBACK_META_MODELS:modelId.slice(5)}});
if(!router.get(modelId).configured)throw new Error('Meta is not configured. No calls made.');
const shows={...existing};
for(const id of ids){
 const item=galleryLessons.find(l=>l.id===id);if(!item)throw new Error(`Unknown gallery lesson ${id}.`);
 // A writer reply that fails the show check is retried once; a second failure skips the
 // lesson and keeps its previous show, so one bad reply never loses the others' work.
 let raw,show;
 for(let attempt=1;attempt<=2&&!show;attempt++){
  const started=performance.now();
  try{raw=await router.call(modelId,showRequest({lesson:item.lesson}));show=readShow(raw,item.lesson);console.log(`${id}: ${show.slides.length} slides in ${Math.round(performance.now()-started)} ms`);}
  catch(error){console.log(`${id}: attempt ${attempt} rejected (${error.message})`);}
 }
 if(!show){console.log(`${id}: kept the previous show`);continue;}
 let cover=null;
 try{const image=await generateMetaImage({apiKey:process.env.MODEL_API_KEY,prompt:show.coverPrompt});
  const base64=image.dataUrl.slice(image.dataUrl.indexOf(',')+1);await writeFile(new URL(`../public/gallery/${id}-cover.${image.format}`,import.meta.url),Buffer.from(base64,'base64'));
  cover=`/gallery/${id}-cover.${image.format}`;console.log(`${id}: cover ${cover} (${Math.round(base64.length*3/4/1024)} kB)`);}
 catch(error){console.log(`${id}: no cover (${error.message})`);}
 const illustrations={};
 for(const index of show.slides.map((s,i)=>s.illustrate?i:-1).filter(i=>i>0)){
  try{const image=await generateMetaImage({apiKey:process.env.MODEL_API_KEY,prompt:illustrationPrompt(show,index)});
   const base64=image.dataUrl.slice(image.dataUrl.indexOf(',')+1);await writeFile(new URL(`../public/gallery/${id}-slide-${index}.${image.format}`,import.meta.url),Buffer.from(base64,'base64'));
   illustrations[index]=`/gallery/${id}-slide-${index}.${image.format}`;console.log(`${id}: slide ${index} illustrated (${Math.round(base64.length*3/4/1024)} kB)`);}
  catch(error){console.log(`${id}: slide ${index} not illustrated (${error.message})`);}
 }
 shows[id]={show,cover,illustrations,model:raw.model??modelId.slice(5),coverModel:cover?'muse-image-1.0':null,createdAt:new Date().toISOString().slice(0,10)};
 await writeFile(new URL('../public/gallery-shows.mjs',import.meta.url),render(shows));console.log(`${id}: saved`);
}
const out=render(shows);
function render(shows){return `// Generated by scripts/make-gallery-shows.mjs (${showPromptVersion}). Narration written by the creator
// model from the reviewed gallery lessons; covers drawn by Muse Image. Playback makes no model call.
export const galleryShows=Object.freeze(${JSON.stringify(shows,null,1)});
export function galleryShow(id){return galleryShows[id]??null;}
export function showIdFromHash(hash){const m=/^#show:([a-z-]+)$/.exec(hash??'');return m&&galleryShows[m[1]]?m[1]:null;}
`;}
await writeFile(new URL('../public/gallery-shows.mjs',import.meta.url),out);
console.log(`wrote public/gallery-shows.mjs (${Object.keys(shows).length} shows)`);
