import {existsSync,mkdirSync,writeFileSync} from 'node:fs';
import {generateMetaImage} from '../src/meta.mjs';
import {ILLUSTRATION_STYLE} from '../src/lesson-show.mjs';
import {galleryLessons} from '../public/gallery-lessons.mjs';
import {evaluationLessons} from '../public/evaluation-lessons.mjs';
import {lessonCovers} from '../public/lesson-covers.mjs';
// Usage: node --env-file=.env.local scripts/lesson-covers.mjs [--live] [--evaluation] [--ids=ID,ID] [--force]
//
// Draws one cover illustration per lesson with Muse Image from the lesson's English title
// and introduction, writes it to public/gallery/covers/<id>.webp and records it in
// public/lesson-covers.mjs, which the library reads for its cards. Without --live nothing
// is sent and the plan is printed. One image request per cover; existing covers are kept
// unless --force is given. Covers are decorative and never reviewed.
export const coverPromptVersion='cover-v1';
const clip=(text,max)=>text.length>max?text.slice(0,max-1).trimEnd()+'…':text;
export function coverPrompt(lesson){
 return clip(`${ILLUSTRATION_STYLE} Subject: ${clip(lesson.title.en,120)}. ${clip(lesson.intro.en,400)}`,1000);
}
export function coverTargets({evaluation=false,ids=[]}={}){
 const all=[...galleryLessons.map(item=>({id:item.id,lesson:item.lesson})),...evaluationLessons.map(item=>({id:item.id,lesson:item.lesson}))];
 const wanted=new Set([...(evaluation?evaluationLessons.map(item=>item.id):[]),...ids]);
 const missing=[...wanted].filter(id=>!all.some(item=>item.id===id));
 if(missing.length)throw new Error(`Unknown lesson ids: ${missing.join(', ')}.`);
 return all.filter(item=>wanted.has(item.id));
}
export function coverModule(covers){
 const sorted=Object.fromEntries(Object.keys(covers).sort().map(id=>[id,covers[id]]));
 return `// Generated by scripts/lesson-covers.mjs; do not edit by hand. Each entry is a cover
// illustration Muse Image drew from a lesson's title and introduction. Covers are
// decorative: nobody reviewed them, and they are not part of any evaluation.
export const lessonCovers=Object.freeze(${JSON.stringify(sorted,null,1)});
export function lessonCover(id){return lessonCovers[id]??null;}
`;
}
if(process.argv[1]&&import.meta.url===new URL(process.argv[1],'file:').href){
 const args=process.argv.slice(2);
 const known=['--live','--evaluation','--ids','--force'];
 if(args.some(a=>!known.includes(a.split('=')[0])))throw new Error('Options: --live, --evaluation, --ids=ID,ID, --force.');
 const ids=(args.find(a=>a.startsWith('--ids='))??'').slice(6).split(',').filter(Boolean);
 const targets=coverTargets({evaluation:args.includes('--evaluation'),ids});
 const force=args.includes('--force');
 const todo=targets.filter(item=>force||!lessonCovers[item.id]);
 console.log(`${targets.length} lesson(s) selected, ${todo.length} to draw${force?' (forced)':''}; one image request each.`);
 for(const item of todo)console.log(` ${item.id}: ${coverPrompt(item.lesson).slice(0,100)}…`);
 if(!args.includes('--live')){console.log('Dry run: nothing sent. Add --live to draw.');process.exit(0);}
 const apiKey=process.env.MODEL_API_KEY?.trim();
 if(!apiKey)throw new Error('MODEL_API_KEY is not set. No calls made.');
 const folder=new URL('../public/gallery/covers/',import.meta.url);
 mkdirSync(folder,{recursive:true});
 const covers={...lessonCovers};
 for(const item of todo){
  const prompt=coverPrompt(item.lesson),started=Date.now();
  const image=await generateMetaImage({apiKey,prompt,size:'1536x1024',outputFormat:'webp',timeoutMs:90_000});
  const b64=image.dataUrl.slice(image.dataUrl.indexOf(',')+1);
  const file=new URL(`${item.id}.webp`,folder);
  writeFileSync(file,Buffer.from(b64,'base64'));
  covers[item.id]={src:`/gallery/covers/${item.id}.webp`,model:image.model,createdAt:new Date().toISOString().slice(0,10),promptVersion:coverPromptVersion};
  writeFileSync(new URL('../public/lesson-covers.mjs',import.meta.url),coverModule(covers));
  console.log(` drew ${item.id} in ${((Date.now()-started)/1000).toFixed(1)} s (${Math.round(Buffer.byteLength(b64,'base64')/1024)} KB)${existsSync(file)?'':' (write failed)'}`);
 }
 console.log(`Done: ${Object.keys(covers).length} cover(s) recorded in public/lesson-covers.mjs.`);
}
